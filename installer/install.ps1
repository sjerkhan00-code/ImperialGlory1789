<#
  Imperial Glory 1789 - offline installer and uninstaller.

  What it does (nothing else, no internet access, no auto-update):
    - finds your Imperial Glory folder (this folder, its parent, the game's registry key, Steam or GOG
      default folders, or it asks you);
    - checks your ImperialGlory.exe (size, MD5, and the original bytes of every patched range);
    - writes a PATCHED COPY named ImperialGlory_ModNations.exe. ImperialGlory.exe is only read, never changed;
    - BUILDS Data2.pak in the game folder from your own original data.pak / Data1.pak / Text.pak plus the mod's
      payload folder (the mod package contains no original game files). Every file is checked by MD5; an existing
      Data2.pak is backed up first;
    - optionally creates a desktop shortcut;
    - uninstall removes ImperialGlory_ModNations.exe and Data2.pak and restores the backups.

  Usage (Install.bat / Uninstall.bat run this for you):
    powershell -NoProfile -ExecutionPolicy Bypass -File install.ps1 [-Uninstall] [-GameDir <folder>]
        [-DryRun] [-DryRunOut <folder>] [-Yes] [-NoShortcut]

    -DryRun     run every check and build the patched exe and Data2.pak, but write NOTHING to the game folder.
                Both go to -DryRunOut (default: %TEMP%\ImperialGlory1789_dryrun) for inspection.
    -Yes        do not ask; take the default answer of every question.
    -NoShortcut never create the desktop shortcut.

  Patch data: patches.json (generated by the mod's build tools from the same patch list as the mod exe).
  Pak data:   manifest.json (every Data2.pak entry: copied from an original pak, an IGD1 delta against an original
              entry, or a new file; size, MD5, CRC and zip header fields) and the payload folder (the new files and
              deltas as loose files 0001.dat ..., each with its size and MD5 in the manifest).
#>
[CmdletBinding()]
param(
    [string]$GameDir = '',
    [switch]$Uninstall,
    [switch]$DryRun,
    [string]$DryRunOut = '',
    [switch]$Yes,
    [switch]$NoShortcut
)

$ErrorActionPreference = 'Stop'

$Here          = Split-Path -Parent $MyInvocation.MyCommand.Path
$SpecPath      = Join-Path $Here 'patches.json'
$ManifestPath  = Join-Path $Here 'manifest.json'
$PayloadName   = 'payload'
$OrigExeName   = 'ImperialGlory.exe'
$ModExeName    = 'ImperialGlory_ModNations.exe'
$PakName       = 'Data2.pak'
$BackupDirName = 'ImperialGlory1789_backup'
$StateName     = 'install_state.json'
$ShortcutName  = 'Imperial Glory 1789.lnk'

# ------------------------------------------------------------------ helpers
function Say([string]$t)  { Write-Host $t }
function Good([string]$t) { Write-Host $t -ForegroundColor Green }
function Warn([string]$t) { Write-Host ('WARNING: ' + $t) -ForegroundColor Yellow }
$script:Touched = $false     # set once a file in the game folder has been written or removed
$script:TempFile = $null     # a temp file of ours in the game folder (the new Data2.pak before it is moved in place)
function Fail([string]$t) {
    if ($script:TempFile) {
        try { if (Test-Path -LiteralPath $script:TempFile) { Remove-Item -LiteralPath $script:TempFile -Force } } catch { }
    }
    Write-Host ''
    Write-Host ('ERROR: ' + $t) -ForegroundColor Red
    if ($script:Touched) {
        Write-Host 'Some files were already changed. Run Uninstall.bat to restore the game folder.' -ForegroundColor Red
    } else {
        Write-Host 'Nothing was changed in the game folder.' -ForegroundColor Red
    }
    exit 1
}

function Ask([string]$question, [bool]$default) {
    if ($Yes) { return $default }
    if ($default) { $hint = '[Y/n]' } else { $hint = '[y/N]' }
    while ($true) {
        $a = Read-Host ($question + ' ' + $hint)
        if ($null -eq $a -or $a.Trim() -eq '') { return $default }
        $a = $a.Trim().ToLower()
        if ($a -eq 'y' -or $a -eq 'yes') { return $true }
        if ($a -eq 'n' -or $a -eq 'no')  { return $false }
    }
}

function Get-Prop($obj, [string]$name) {
    if ($null -eq $obj) { return $null }
    $p = $obj.PSObject.Properties[$name]
    if ($null -eq $p) { return $null }
    return $p.Value
}

function Get-MD5Bytes([byte[]]$bytes) {
    $m = [System.Security.Cryptography.MD5]::Create()
    try { return ([BitConverter]::ToString($m.ComputeHash($bytes))).Replace('-', '').ToLower() }
    finally { $m.Dispose() }
}

function Get-MD5File([string]$path) {
    return (Get-FileHash -LiteralPath $path -Algorithm MD5).Hash.ToLower()
}

function Convert-HexToBytes([string]$hex) {
    $n = [int]($hex.Length / 2)
    $b = New-Object byte[] $n
    for ($i = 0; $i -lt $n; $i++) { $b[$i] = [Convert]::ToByte($hex.Substring(2 * $i, 2), 16) }
    return ,$b
}

function Get-FullPath([string]$p) { return [System.IO.Path]::GetFullPath($p).TrimEnd('\') }

function Same-Path([string]$a, [string]$b) {
    return [string]::Equals((Get-FullPath $a), (Get-FullPath $b), [StringComparison]::OrdinalIgnoreCase)
}

function Read-Spec {
    if (-not (Test-Path -LiteralPath $SpecPath)) { Fail "patches.json is missing next to install.ps1 ($Here)." }
    $s = Get-Content -LiteralPath $SpecPath -Raw | ConvertFrom-Json
    if ((Get-Prop $s 'format') -ne 1) { Fail 'patches.json has an unknown format.' }
    return $s
}

function Read-Manifest {
    if (-not (Test-Path -LiteralPath $ManifestPath)) { Fail "manifest.json is missing next to install.ps1 ($Here). Extract the whole archive first." }
    $m = Get-Content -LiteralPath $ManifestPath -Raw | ConvertFrom-Json
    if ((Get-Prop $m 'kind') -ne 'ig1789-data2-manifest' -or (Get-Prop $m 'format') -ne 1) { Fail 'manifest.json has an unknown format.' }
    return $m
}

# ------------------------------------------------------------------ Data2.pak, built from the original paks
# The game reads paks with its own ZIP reader: central directory, then each local header's sizes; stored (0) or
# deflate (8) only, no ZIP64. Build-Pak writes exactly the entry names, order and header fields of the tested
# Data2.pak (from manifest.json). .NET's DeflateStream (Optimal) gives the same bytes as the mod's build tools, so
# the result is normally byte-identical to the tested pak; otherwise Test-BuiltPak checks every entry by MD5.
$script:Md5 = $null
function Get-Hex([byte[]]$bytes) {
    if ($null -eq $script:Md5) { $script:Md5 = [System.Security.Cryptography.MD5]::Create() }
    return ([BitConverter]::ToString($script:Md5.ComputeHash($bytes))).Replace('-', '').ToLower()
}

function Open-Zip([string]$path) {
    $fs = [System.IO.File]::Open($path, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::Read)
    try { return (New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Read, $false)) }
    catch { $fs.Dispose(); throw }
}

function Get-ZipIndex($zip) {
    # name -> entry, case-insensitive with '/' separators (the game's own pak lookup is case-insensitive too)
    $d = New-Object 'System.Collections.Generic.Dictionary[string,object]' ([StringComparer]::OrdinalIgnoreCase)
    foreach ($e in $zip.Entries) {
        $k = $e.FullName.Replace('\', '/')
        if (-not $d.ContainsKey($k)) { $d[$k] = $e }
    }
    return ,$d
}

function Read-ZipEntry($entry) {
    $n = [int]$entry.Length
    $buf = New-Object byte[] $n
    $s = $entry.Open()
    try {
        $o = 0
        while ($o -lt $n) {
            $r = $s.Read($buf, $o, $n - $o)
            if ($r -le 0) { break }
            $o += $r
        }
    } finally { $s.Dispose() }
    if ($o -ne $n) { throw ('short read of ' + $entry.FullName) }
    return ,$buf
}

function Read-Payload($e) {
    # one loose file of the payload folder (manifest: payload = 'payload/0001.dat', psize, pmd5); checked before use
    $path = Join-Path $Here ([string]$e.payload).Replace('/', '\')
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "The '$PayloadName' folder is incomplete. Extract the whole archive again." }
    $b = [System.IO.File]::ReadAllBytes($path)
    if ($b.Length -ne [int64]$e.psize -or (Get-Hex $b) -ne $e.pmd5) { throw ("{0} is damaged (MD5 mismatch). Download the mod again." -f $e.payload) }
    return ,$b
}

function Expand-Delta([byte[]]$src, [byte[]]$d) {
    # IGD1: 'IGD1', u32 source length, u32 target length, ops: 1 COPY(u32 offset, u32 length) | 2 INSERT(u32 length,
    # bytes) | 0 END (the last byte). Same checks as tools/igdelta.py apply().
    if ($d.Length -lt 13 -or $d[0] -ne 0x49 -or $d[1] -ne 0x47 -or $d[2] -ne 0x44 -or $d[3] -ne 0x31) { throw 'not an IGD1 delta' }
    if ([BitConverter]::ToUInt32($d, 4) -ne $src.Length) { throw 'delta source length mismatch' }
    $tl = [int][BitConverter]::ToUInt32($d, 8)
    $out = New-Object byte[] $tl
    $p = 12; $w = 0; $n = $d.Length
    while ($true) {
        if ($p -ge $n) { throw 'delta truncated' }
        $op = $d[$p]
        if ($op -eq 1) {
            $o = [BitConverter]::ToInt32($d, $p + 1); $k = [BitConverter]::ToInt32($d, $p + 5)
            if ($o -lt 0 -or $k -lt 0 -or $o + $k -gt $src.Length -or $w + $k -gt $tl) { throw 'delta COPY out of range' }
            [Array]::Copy($src, $o, $out, $w, $k); $w += $k; $p += 9
        } elseif ($op -eq 2) {
            $k = [BitConverter]::ToInt32($d, $p + 1)
            if ($k -lt 0 -or $p + 5 + $k -gt $n -or $w + $k -gt $tl) { throw 'delta INSERT out of range' }
            [Array]::Copy($d, $p + 5, $out, $w, $k); $w += $k; $p += 5 + $k
        } elseif ($op -eq 0) {
            $p += 1
            break
        } else { throw ('bad delta op ' + $op) }
    }
    if ($w -ne $tl -or $p -ne $n) { throw 'delta length mismatch' }
    return ,$out
}

function Compress-Deflate([byte[]]$b) {
    if ($b.Length -eq 0) { return ,([byte[]](3, 0)) }     # what zlib writes for empty input (the dir entries)
    $ms = New-Object System.IO.MemoryStream
    $ds = New-Object System.IO.Compression.DeflateStream($ms, [System.IO.Compression.CompressionLevel]::Optimal, $true)
    $ds.Write($b, 0, $b.Length)
    $ds.Dispose()
    return ,$ms.ToArray()
}

function Test-SourcePaks([string]$dir, $man) {
    foreach ($p in $man.sources.PSObject.Properties) {
        $path = Join-Path $dir $p.Name
        if (-not (Test-Path -LiteralPath $path)) {
            Fail ("{0} is missing in {1}. The installer builds Data2.pak from your original game files (data.pak, Data1.pak, Text.pak of Imperial Glory v1.1). Restore them (Steam: Verify integrity of game files) and run the installer again." -f $p.Name, $dir)
        }
        if ((Get-Item -LiteralPath $path).Length -ne [int64]$p.Value.size) {
            Say ("Note: your {0} differs in size from the Steam v1.1 file; its contents are checked file by file." -f $p.Name)
        }
    }
}

function Build-Pak([string]$dir, $man, [string]$outPath) {
    # Writes the new Data2.pak to $outPath. Throws with a message for the user on any problem.
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $zc = $man.zip
    $srcZip = @{}; $srcIdx = @{}
    $fs = $null
    try {
        foreach ($p in $man.sources.PSObject.Properties) {
            try { $z = Open-Zip (Join-Path $dir $p.Name) }
            catch { throw ("{0} cannot be read as a pak (damaged?): {1}" -f $p.Name, $_.Exception.Message) }
            $srcZip[$p.Name] = $z
            $srcIdx[$p.Name] = Get-ZipIndex $z
        }
        $entries = @($man.entries)
        if ($entries.Count -gt 65535) { throw 'too many entries' }
        $fs = [System.IO.File]::Open($outPath, [System.IO.FileMode]::Create, [System.IO.FileAccess]::Write, [System.IO.FileShare]::None)
        $bw = New-Object System.IO.BinaryWriter($fs)
        $cd = New-Object System.IO.MemoryStream
        $cw = New-Object System.IO.BinaryWriter($cd)
        $ascii = [System.Text.Encoding]::ASCII
        $empty = New-Object byte[] 0
        $i = 0; $step = [math]::Max(1, [int]($entries.Count / 10))
        foreach ($e in $entries) {
            $i++
            if ($i % $step -eq 0) {
                Write-Progress -Activity "Building $PakName" -Status ("{0} of {1} files" -f $i, $entries.Count) -PercentComplete (100 * $i / $entries.Count)
            }
            $kind = [string]$e.kind
            $crc = [uint32]0
            $data = $empty
            if ($kind -ne 'dir') {
                $src = $null
                if ($kind -eq 'copy' -or $kind -eq 'delta') {
                    $pk = [string]$e.pak
                    $from = ([string](Get-Prop $e 'from')).Replace('\', '/')
                    if (-not $srcIdx[$pk].ContainsKey($from)) { throw ("{0} is not the original v1.1 file: it has no '{1}'." -f $pk, $from) }
                    $src = Read-ZipEntry $srcIdx[$pk][$from]
                }
                if ($kind -eq 'copy') {
                    $data = $src
                } elseif ($kind -eq 'delta') {
                    if ($src.Length -ne [int64]$e.from_size -or (Get-Hex $src) -ne $e.from_md5) {
                        throw ("{0} is not the original v1.1 file: '{1}' has different contents." -f $e.pak, $e.from)
                    }
                    $d = Read-Payload $e
                    try { $data = Expand-Delta $src $d }
                    catch { throw ("{0} could not be rebuilt ({1}). Download the mod again." -f $e.name, $_.Exception.Message) }
                } elseif ($kind -eq 'new') {
                    $data = Read-Payload $e
                } else { throw ('manifest.json: unknown entry kind ' + $kind) }
                if ($data.Length -ne [int64]$e.size -or (Get-Hex $data) -ne $e.md5) {
                    if ($kind -eq 'copy') { throw ("{0} is not the original v1.1 file: '{1}' has different contents." -f $e.pak, $e.from) }
                    throw ("{0} came out wrong (MD5 mismatch). Download the mod again." -f $e.name)
                }
                $crc = [uint32]$e.crc
            }
            $comp = Compress-Deflate $data
            $nm = $ascii.GetBytes([string]$e.name)
            $off = $fs.Position
            if ($off -gt [int64]4294967295) { throw 'Data2.pak would be larger than 4 GB' }
            $t = [uint32]$e.time
            $bw.Write([uint32]0x04034b50); $bw.Write([uint16]$zc.version_needed); $bw.Write([uint16]$zc.flags)
            $bw.Write([uint16]$zc.method); $bw.Write($t); $bw.Write($crc); $bw.Write([uint32]$comp.Length)
            $bw.Write([uint32]$data.Length); $bw.Write([uint16]$nm.Length); $bw.Write([uint16]0)
            $bw.Write($nm); $bw.Write($comp)
            $cw.Write([uint32]0x02014b50); $cw.Write([byte]$zc.version_made); $cw.Write([byte]$zc.system_made)
            $cw.Write([uint16]$zc.version_needed); $cw.Write([uint16]$zc.flags); $cw.Write([uint16]$zc.method)
            $cw.Write($t); $cw.Write($crc); $cw.Write([uint32]$comp.Length); $cw.Write([uint32]$data.Length)
            $cw.Write([uint16]$nm.Length); $cw.Write([uint16]0); $cw.Write([uint16]0); $cw.Write([uint16]0)
            $cw.Write([uint16]0); $cw.Write([uint32]$e.attr); $cw.Write([uint32]$off); $cw.Write($nm)
        }
        $cdo = $fs.Position
        $cw.Flush()
        $cdb = $cd.ToArray()
        $bw.Write($cdb)
        $bw.Write([uint32]0x06054b50); $bw.Write([uint16]0); $bw.Write([uint16]0)
        $bw.Write([uint16]$entries.Count); $bw.Write([uint16]$entries.Count)
        $bw.Write([uint32]$cdb.Length); $bw.Write([uint32]$cdo); $bw.Write([uint16]0)
        $bw.Flush()
    } finally {
        Write-Progress -Activity "Building $PakName" -Completed
        if ($fs) { $fs.Dispose() }
        foreach ($z in $srcZip.Values) { $z.Dispose() }
    }
    return $sw.Elapsed.TotalSeconds
}

function Test-BuiltPak([string]$path, $man) {
    # Read the new pak back with .NET's own zip reader: same entries in the same order, every file's MD5.
    $z = Open-Zip $path
    try {
        $list = $z.Entries
        $entries = @($man.entries)
        if ($list.Count -ne $entries.Count) { throw ("the new {0} has {1} entries instead of {2}" -f $PakName, $list.Count, $entries.Count) }
        for ($i = 0; $i -lt $entries.Count; $i++) {
            $e = $entries[$i]
            if ($list[$i].FullName -ne $e.name) { throw ("entry {0} of the new {1} is '{2}' instead of '{3}'" -f $i, $PakName, $list[$i].FullName, $e.name) }
            if ($e.kind -eq 'dir') { continue }
            $b = Read-ZipEntry $list[$i]
            if ($b.Length -ne [int64]$e.size -or (Get-Hex $b) -ne $e.md5) { throw ("'{0}' in the new {1} is wrong (MD5)" -f $e.name, $PakName) }
        }
    } finally { $z.Dispose() }
}

function New-Pak([string]$dir, $man, [string]$outPath) {
    # Build + verify. Returns the MD5 of the new pak; removes $outPath and fails with a message on any problem.
    Say ("Building {0} from your original game files ({1} files; this takes about a minute) ..." -f $PakName, $man.pak.files)
    try {
        $secs = Build-Pak $dir $man $outPath
        $m = Get-MD5File $outPath
        if ($m -eq $man.pak.md5) {
            Good ("Built {0} in {1:N0} s; it is byte-identical to the tested one (MD5 {2})." -f $PakName, $secs, $m)
        } else {
            Say ("Built {0} in {1:N0} s; its compression differs from the tested file, checking every file ..." -f $PakName, $secs)
            Test-BuiltPak $outPath $man
            Good ("All {0} files of the new {1} are verified (MD5)." -f $man.pak.files, $PakName)
        }
        return $m
    } catch {
        $msg = $_.Exception.Message
        try { if (Test-Path -LiteralPath $outPath) { Remove-Item -LiteralPath $outPath -Force } } catch { }
        if ($msg -match 'not the original') { $msg += ' Restore the original game files (Steam: Verify integrity of game files; GOG: Verify / Repair) and run the installer again.' }
        Fail ("Building {0} failed: {1}" -f $PakName, $msg)
    }
}

function Test-PakCurrent([string]$path, $man, $state) {
    # True when the game folder's Data2.pak already is this mod version (the tested bytes, or the pak this installer
    # built last time for the same manifest).
    if (-not (Test-Path -LiteralPath $path)) { return $false }
    $m = Get-MD5File $path
    if ($m -eq $man.pak.md5) { return $true }
    return ((Get-Prop $state 'pak_ref') -eq $man.pak.md5 -and (Get-Prop $state 'pak_md5') -eq $m)
}

# ------------------------------------------------------------------ game folder
function Test-GameDir([string]$d) {
    if ([string]::IsNullOrWhiteSpace($d)) { return $false }
    try {
        return ((Test-Path -LiteralPath (Join-Path $d $OrigExeName)) -and (Test-Path -LiteralPath (Join-Path $d 'data.pak')))
    } catch { return $false }
}

function Get-RegValue([string]$key, [string]$name) {
    try {
        if (-not (Test-Path -LiteralPath $key)) { return $null }
        return Get-Prop (Get-ItemProperty -LiteralPath $key) $name
    } catch { return $null }
}

function Get-Candidates {
    $c = New-Object System.Collections.Generic.List[string]
    $c.Add($Here)
    $c.Add((Split-Path -Parent $Here))
    foreach ($k in @('HKCU:\Software\Pyro Studios\Imperial Glory\Game',
                     'HKLM:\SOFTWARE\WOW6432Node\Pyro Studios\Imperial Glory\Game',
                     'HKLM:\SOFTWARE\Pyro Studios\Imperial Glory\Game')) {
        $v = Get-RegValue $k 'Path'
        if ($v) { $c.Add([string]$v) }
    }
    $steamRoots = New-Object System.Collections.Generic.List[string]
    foreach ($kv in @(@('HKCU:\Software\Valve\Steam', 'SteamPath'),
                      @('HKLM:\SOFTWARE\WOW6432Node\Valve\Steam', 'InstallPath'),
                      @('HKLM:\SOFTWARE\Valve\Steam', 'InstallPath'))) {
        $v = Get-RegValue $kv[0] $kv[1]
        if ($v) { $steamRoots.Add(([string]$v).Replace('/', '\')) }
    }
    $pf86 = ${env:ProgramFiles(x86)}
    if (-not $pf86) { $pf86 = 'C:\Program Files (x86)' }
    $steamRoots.Add((Join-Path $pf86 'Steam'))
    foreach ($r in @($steamRoots)) {
        $c.Add((Join-Path $r 'steamapps\common\Imperial Glory'))
        $vdf = Join-Path $r 'steamapps\libraryfolders.vdf'
        try {
            if (Test-Path -LiteralPath $vdf) {
                foreach ($m in [regex]::Matches((Get-Content -LiteralPath $vdf -Raw), '"path"\s+"([^"]+)"')) {
                    $lib = $m.Groups[1].Value.Replace('\\', '\')
                    $c.Add((Join-Path $lib 'steamapps\common\Imperial Glory'))
                }
            }
        } catch { }
    }
    try {
        foreach ($g in @(Get-ChildItem -LiteralPath 'HKLM:\SOFTWARE\WOW6432Node\GOG.com\Games' -ErrorAction SilentlyContinue)) {
            $p = Get-ItemProperty -LiteralPath $g.PSPath
            if ((Get-Prop $p 'gameName') -like '*Imperial Glory*' -and (Get-Prop $p 'path')) { $c.Add([string](Get-Prop $p 'path')) }
        }
    } catch { }
    $c.Add('C:\GOG Games\Imperial Glory')
    $c.Add((Join-Path $pf86 'GOG Galaxy\Games\Imperial Glory'))
    $c.Add((Join-Path $pf86 'GOG.com\Imperial Glory'))
    $c.Add((Join-Path $pf86 'Eidos\Imperial Glory'))
    return $c
}

function Find-GameDir {
    if ($GameDir) {
        if (Test-GameDir $GameDir) { return (Get-FullPath $GameDir) }
        Fail "No $OrigExeName and data.pak in '$GameDir'."
    }
    $found = $null
    foreach ($d in (Get-Candidates)) {
        if (Test-GameDir $d) { $found = Get-FullPath $d; break }
    }
    if ($found) {
        Say "Game folder found: $found"
        if (Ask 'Use this folder?' $true) { return $found }
    } else {
        Say 'The Imperial Glory folder was not found automatically.'
    }
    if ($Yes) { Fail 'No game folder (use -GameDir <folder>).' }
    while ($true) {
        $d = Read-Host 'Paste the full path of your Imperial Glory folder (the one with ImperialGlory.exe), or press Enter to quit'
        if ([string]::IsNullOrWhiteSpace($d)) { Fail 'No game folder given.' }
        $d = $d.Trim().Trim('"')
        if (Test-GameDir $d) { return (Get-FullPath $d) }
        Warn "No $OrigExeName and data.pak in '$d'."
    }
}

# ------------------------------------------------------------------ install state (backups)
function Read-State([string]$dir) {
    $p = Join-Path (Join-Path $dir $BackupDirName) $StateName
    if (-not (Test-Path -LiteralPath $p)) { return $null }
    try { return (Get-Content -LiteralPath $p -Raw | ConvertFrom-Json) } catch { Warn "Unreadable $p, ignored."; return $null }
}

function Write-State([string]$dir, $state) {
    $bdir = Join-Path $dir $BackupDirName
    if (-not (Test-Path -LiteralPath $bdir)) { New-Item -ItemType Directory -Path $bdir | Out-Null }
    $state | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $bdir $StateName) -Encoding UTF8
}

function Get-StateList($state, [string]$name) {
    $v = Get-Prop $state $name
    if ($null -eq $v) { return @() }
    return @($v)
}

# ------------------------------------------------------------------ patch
function Invoke-Patch([byte[]]$exe, $spec) {
    # Every range must hold one of its accepted original byte strings ('expect'). A range marked 'replace_any'
    # (the fullscreen resolution table: pure data, fully overwritten) accepts any content; the MD5 of the result
    # decides then whether this exe is a tested one.
    $bad = New-Object System.Collections.Generic.List[string]
    $notes = New-Object System.Collections.Generic.List[string]
    foreach ($r in $spec.ranges) {
        $cur = ([BitConverter]::ToString($exe, [int]$r.off, [int]$r.len)).Replace('-', '').ToLower()
        if (@($r.expect) -notcontains $cur) {
            $msg = '{0} ({1} bytes, patch {2})' -f $r.va, $r.len, (@($r.patches) -join ',')
            if (Get-Prop $r 'replace_any') { $notes.Add($msg) } else { $bad.Add($msg) }
        }
    }
    if ($bad.Count -gt 0) { return @{ Bytes = $null; Bad = $bad; Notes = $notes } }
    $out = [byte[]]$exe.Clone()
    foreach ($r in $spec.ranges) {
        $new = Convert-HexToBytes $r.new
        [Array]::Copy($new, 0, $out, [int]$r.off, $new.Length)
    }
    return @{ Bytes = $out; Bad = $bad; Notes = $notes }
}

function Test-Writable([string]$dir) {
    $t = Join-Path $dir ('.ig1789_write_test_' + [guid]::NewGuid().ToString('N'))
    try { [System.IO.File]::WriteAllBytes($t, [byte[]]@(0)); Remove-Item -LiteralPath $t -Force; return $true }
    catch { return $false }
}

function Test-GameRunning([string]$dir) {
    # True when a game process runs from this folder (or its path cannot be read: then assume it does).
    foreach ($p in @(Get-Process -Name 'ImperialGlory', 'ImperialGlory_ModNations' -ErrorAction SilentlyContinue)) {
        $exe = $null
        try { $exe = $p.Path } catch { }
        if (-not $exe) { return $true }
        if (Same-Path (Split-Path -Parent $exe) $dir) { return $true }
    }
    return $false
}

# ------------------------------------------------------------------ install
function Invoke-Install {
    $spec = Read-Spec
    $man = Read-Manifest
    Say ''
    Say ("Installing {0} {1}" -f $spec.mod, $spec.version)
    if ($DryRun) { Say 'DRY RUN: nothing will be written to the game folder.' }
    try { Add-Type -AssemblyName System.IO.Compression }
    catch { Fail ('.NET System.IO.Compression is not available (.NET Framework 4.5 or newer is needed; Windows 8, 10 and 11 have it): ' + $_.Exception.Message) }

    $payload = Join-Path $Here $PayloadName
    if (-not (Test-Path -LiteralPath $payload -PathType Container)) { Fail "The '$PayloadName' folder is missing next to install.ps1. Extract the whole archive first." }
    Say "Checking the $PayloadName folder ..."
    $pf = @(Get-ChildItem -LiteralPath $payload -File)
    $psum = [int64]0; foreach ($f in $pf) { $psum += $f.Length }
    if ($pf.Count -ne [int]$man.payload.files -or $psum -ne [int64]$man.payload.size) {
        Fail "The '$PayloadName' folder is incomplete or damaged ($($pf.Count) of $($man.payload.files) files). Extract the whole archive again."
    }

    $dir = Find-GameDir
    $exePath = Join-Path $dir $OrigExeName
    $modExe  = Join-Path $dir $ModExeName
    $pakDst  = Join-Path $dir $PakName
    if (Same-Path $exePath $modExe) { Fail 'Internal error: the output would overwrite ImperialGlory.exe.' }

    $data1 = Join-Path $dir 'Data1.pak'
    if (-not (Test-Path -LiteralPath $data1)) {
        Fail 'Data1.pak (the official v1.1 patch data) is missing. Without it the game ignores Data2.pak. Install the v1.1 patch first (Steam and GOG include it).'
    }
    Test-SourcePaks $dir $man

    Say "Checking $OrigExeName ..."
    $exe = [System.IO.File]::ReadAllBytes($exePath)
    if ($exe.Length -ne [int]$spec.input.size) {
        Fail ("$OrigExeName has {0} bytes; the mod needs the v1.1 exe with {1} bytes (Steam / GOG). Restore the original exe (Steam: Verify integrity of game files) and run the installer again." -f $exe.Length, $spec.input.size)
    }
    $inMd5 = Get-MD5Bytes $exe
    $known = $null
    foreach ($v in $spec.input.variants) { if ($v.md5 -eq $inMd5) { $known = $v } }
    if ($known) { Good ("Recognised: {0} (MD5 {1})" -f $known.name, $inMd5) }
    else { Warn ("Unknown $OrigExeName (MD5 $inMd5). Checking every patched range ...") }

    $res = Invoke-Patch $exe $spec
    if ($res.Bad.Count -gt 0) {
        Say ''
        foreach ($b in $res.Bad) { Say ('  unexpected bytes at ' + $b) }
        Fail ("{0} of {1} patch ranges do not match this $OrigExeName. It is not a supported v1.1 exe (or it was modified by another mod). Restore the original exe (Steam: Verify integrity of game files) and try again." -f $res.Bad.Count, @($spec.ranges).Count)
    }
    $outMd5 = Get-MD5Bytes $res.Bytes
    if ($outMd5 -eq $spec.output.md5) {
        if ($res.Notes.Count -gt 0) { Say 'Your exe had a custom fullscreen resolution table; the mod replaces it with its own list.' }
        Good ("All {0} patch ranges verified; the patched exe is identical to the tested one (MD5 {1})." -f @($spec.ranges).Count, $outMd5)
    } elseif ($known) {
        Fail 'Internal error: the patched exe has an unexpected MD5.'
    } else {
        Warn 'All patch ranges match, but other parts of this exe differ from the tested versions. The mod may not work.'
        if (-not (Ask 'Continue anyway?' $false)) { Fail 'Cancelled.' }
    }

    if ($DryRun) {
        $od = $DryRunOut
        if (-not $od) { $od = Join-Path $env:TEMP 'ImperialGlory1789_dryrun' }
        if (Same-Path $od $dir) { Fail 'Dry run: -DryRunOut must not be the game folder.' }
        if (-not (Test-Path -LiteralPath $od)) { New-Item -ItemType Directory -Path $od | Out-Null }
        $o = Join-Path $od $ModExeName
        [System.IO.File]::WriteAllBytes($o, $res.Bytes)
        Good "DRY RUN: patched exe written to $o (not to the game folder)."
        $po = Join-Path $od $PakName
        $null = New-Pak $dir $man $po
        Good "DRY RUN: $PakName written to $po (not to the game folder)."
        $st = Read-State $dir
        foreach ($f in @($ModExeName, $PakName)) {
            $p = Join-Path $dir $f
            if (-not (Test-Path -LiteralPath $p)) { Say "Would create $p."; continue }
            if ($f -eq $ModExeName) { $cur = ((Get-MD5File $p) -eq $outMd5) } else { $cur = (Test-PakCurrent $p $man $st) }
            if ($cur) { Say "Would keep $p (already this version)." }
            elseif ((Get-StateList $st 'installed') -contains $f) { Say "Would replace $p (an older version of this mod)." }
            else { Say "Would back up the existing $p to $BackupDirName\ and replace it." }
        }
        Good 'DRY RUN finished.'
        return
    }

    if (Test-GameRunning $dir) { Fail 'Imperial Glory is running. Close the game first.' }
    if (-not (Test-Writable $dir)) {
        Fail "Cannot write to $dir. Right-click Install.bat and choose 'Run as administrator'."
    }

    $bdir = Join-Path $dir $BackupDirName
    $state = Read-State $dir
    $installed = @(Get-StateList $state 'installed')
    $backups = @(Get-StateList $state 'backups')

    # Data2.pak: built into a temp file first, so a failure leaves the game folder as it was
    $pakCurrent = Test-PakCurrent $pakDst $man $state
    $pakTmp = $pakDst + '.tmp'
    if ($pakCurrent) { $pakMd5 = Get-MD5File $pakDst }
    else {
        $script:TempFile = $pakTmp
        $pakMd5 = New-Pak $dir $man $pakTmp
    }

    # backups of files this mod did not install itself
    foreach ($f in @($PakName, $ModExeName)) {
        $p = Join-Path $dir $f
        if (-not (Test-Path -LiteralPath $p)) { continue }
        if ($installed -contains $f) { continue }                                  # ours (an earlier install): replaced, no backup
        if ($f -eq $PakName -and $pakCurrent) { continue }                         # already this version
        if ($f -eq $ModExeName -and (Get-MD5File $p) -eq $outMd5) { continue }    # already this version
        if (-not (Test-Path -LiteralPath $bdir)) { New-Item -ItemType Directory -Path $bdir | Out-Null }
        $bname = $f
        if (Test-Path -LiteralPath (Join-Path $bdir $bname)) { $bname = $f + '.' + (Get-Date -Format 'yyyyMMdd_HHmmss') }
        Copy-Item -LiteralPath $p -Destination (Join-Path $bdir $bname)
        $backups += [pscustomobject]@{ file = $f; backup = $bname }
        Say ("Backed up the existing {0} to {1}\{2}" -f $f, $BackupDirName, $bname)
    }

    # the mod exe (a new file; ImperialGlory.exe is never written)
    $tmp = $modExe + '.tmp'
    $script:Touched = $true
    [System.IO.File]::WriteAllBytes($tmp, $res.Bytes)
    Move-Item -LiteralPath $tmp -Destination $modExe -Force
    if ((Get-MD5File $modExe) -ne $outMd5) { Fail "Writing $modExe failed." }
    Good "Wrote $modExe"

    # Data2.pak
    if ($pakCurrent) {
        Good "$PakName is already up to date."
    } else {
        Move-Item -LiteralPath $pakTmp -Destination $pakDst -Force
        $script:TempFile = $null
        if ((Get-MD5File $pakDst) -ne $pakMd5) { Fail "Writing $pakDst failed." }
        Good "Wrote $pakDst"
    }

    $lnkPath = Get-Prop $state 'shortcut'
    if (-not $NoShortcut -and (Ask 'Create a desktop shortcut "Imperial Glory 1789"?' $true)) {
        try {
            $lnkPath = Join-Path ([Environment]::GetFolderPath('Desktop')) $ShortcutName
            $sh = New-Object -ComObject WScript.Shell
            $s = $sh.CreateShortcut($lnkPath)
            $s.TargetPath = $modExe
            $s.WorkingDirectory = $dir
            $s.IconLocation = $modExe + ',0'
            $s.Description = 'Imperial Glory 1789 (mod)'
            $s.Save()
            Good "Created the shortcut $lnkPath"
        } catch { Warn ('Could not create the shortcut: ' + $_.Exception.Message); $lnkPath = $null }
    }

    $newState = [ordered]@{
        mod       = $spec.mod
        version   = $spec.version
        date      = (Get-Date -Format 'yyyy-MM-dd HH:mm')
        installed = @($ModExeName, $PakName)
        backups   = @($backups)
        shortcut  = $lnkPath
        exe_md5   = $outMd5
        pak_md5   = $pakMd5
        pak_ref   = $man.pak.md5
    }
    Write-State $dir ([pscustomobject]$newState)

    Say ''
    Good ("{0} {1} is installed." -f $spec.mod, $spec.version)
    Say "Start the game with $ModExeName (or the desktop shortcut) and begin a NEW campaign."
    Say 'Note: while the mod is installed, the original ImperialGlory.exe also reads Data2.pak. Uninstall to play the unmodded game.'
}

# ------------------------------------------------------------------ uninstall
function Invoke-Uninstall {
    $spec = $null
    if (Test-Path -LiteralPath $SpecPath) { $spec = Read-Spec }
    Say ''
    Say 'Uninstalling Imperial Glory 1789'
    if ($DryRun) { Say 'DRY RUN: nothing will be removed.' }
    $dir = Find-GameDir
    $state = Read-State $dir
    $installed = @(Get-StateList $state 'installed')
    if (-not $DryRun) {
        if (Test-GameRunning $dir) { Fail 'Imperial Glory is running. Close the game first.' }
        if (-not (Test-Writable $dir)) { Fail "Cannot write to $dir. Right-click Uninstall.bat and choose 'Run as administrator'." }
    }
    # MD5s this mod writes: the patched exe; the tested Data2.pak, or the one the installer built (install_state.json)
    $knownMd5 = @{}
    if ($spec) { $knownMd5[$ModExeName] = @($spec.output.md5) }
    $pakMd5s = @()
    if (Test-Path -LiteralPath $ManifestPath) { $pakMd5s += (Read-Manifest).pak.md5 }
    if (Get-Prop $state 'pak_md5') { $pakMd5s += (Get-Prop $state 'pak_md5') }
    if ($pakMd5s.Count -gt 0) { $knownMd5[$PakName] = $pakMd5s }
    foreach ($t in @(($ModExeName + '.tmp'), ($PakName + '.tmp'))) {      # leftovers of an interrupted install
        $p = Join-Path $dir $t
        if (Test-Path -LiteralPath $p) {
            if ($DryRun) { Say "Would remove the leftover $p" } else { $script:Touched = $true; Remove-Item -LiteralPath $p -Force; Good "Removed the leftover $p" }
        }
    }
    $removed = @()
    foreach ($name in @($ModExeName, $PakName)) {
        $p = Join-Path $dir $name
        if (-not (Test-Path -LiteralPath $p)) { Say "$name is not installed."; continue }
        $ours = ($installed -contains $name)
        # the state file says we installed it, but the file may have been replaced since (e.g. by another mod)
        if ($knownMd5.ContainsKey($name)) { $ours = (@($knownMd5[$name]) -contains (Get-MD5File $p)) }
        if (-not $ours) {
            Warn "$p was not installed by this mod (or by a different version)."
            if (-not (Ask "Remove $name anyway?" $false)) { continue }
        }
        $removed += $name
        if ($DryRun) { Say "Would remove $p"; continue }
        $script:Touched = $true
        Remove-Item -LiteralPath $p -Force
        Good "Removed $p"
    }
    $bdir = Join-Path $dir $BackupDirName
    foreach ($b in @(Get-StateList $state 'backups')) {
        $src = Join-Path $bdir $b.backup
        $dst = Join-Path $dir $b.file
        if (-not (Test-Path -LiteralPath $src)) { Warn "Backup $src is missing."; continue }
        if ((Test-Path -LiteralPath $dst) -and -not ($DryRun -and $removed -contains $b.file)) { Warn "$dst exists, the backup stays in $bdir."; continue }
        if ($DryRun) { Say "Would restore $dst from $src"; continue }
        Move-Item -LiteralPath $src -Destination $dst
        Good "Restored $dst"
    }
    $lnk = Get-Prop $state 'shortcut'
    if ($lnk -and (Test-Path -LiteralPath $lnk)) {
        try {
            $t = (New-Object -ComObject WScript.Shell).CreateShortcut($lnk).TargetPath
            if (Same-Path $t (Join-Path $dir $ModExeName)) {
                if ($DryRun) { Say "Would remove the shortcut $lnk" } else { Remove-Item -LiteralPath $lnk -Force; Good "Removed the shortcut $lnk" }
            }
        } catch { Warn ('Could not check the shortcut: ' + $_.Exception.Message) }
    }
    if (-not $DryRun -and (Test-Path -LiteralPath $bdir)) {
        $sp = Join-Path $bdir $StateName
        if (Test-Path -LiteralPath $sp) { Remove-Item -LiteralPath $sp -Force }
        if (@(Get-ChildItem -LiteralPath $bdir -Force).Count -eq 0) { Remove-Item -LiteralPath $bdir -Force }
        else { Warn "Some files were left in $bdir." }
    }
    Say ''
    if ($DryRun) { Good 'DRY RUN finished.' } else { Good 'Imperial Glory 1789 is uninstalled. ImperialGlory.exe was never changed.' }
}

# ------------------------------------------------------------------ main
Say '================================================'
Say ' Imperial Glory 1789 - installer (offline)'
Say '================================================'
if ($Uninstall) { Invoke-Uninstall; exit 0 }
if ($Yes -or $DryRun -or $GameDir) { Invoke-Install; exit 0 }
Say '  1 = install or update'
Say '  2 = uninstall'
Say '  3 = quit'
$choice = Read-Host 'Choose 1, 2 or 3'
if ($null -eq $choice) { $choice = '' }
switch ($choice.Trim()) {
    '1' { Invoke-Install }
    '2' { Invoke-Uninstall }
    default { Say 'Nothing done.' }
}
exit 0
